def suma(a, b):
    """Devuelve la suma de dos números.

    Args:
        a (int | float): Primer sumando.
        b (int | float): Segundo sumando.

    Returns:
        int | float: Resultado de a + b.
    """
    return a + b


def resta(a, b):
    """Devuelve la resta de dos números.

    Args:
        a (int | float): Minuendo.
        b (int | float): Sustraendo.

    Returns:
        int | float: Resultado de a - b.
    """
    return a - b
